import { test, expect } from './canvas-fixture'

test('shared view commands, calibrated ruler, projection framing and revision shortcuts', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open', exact: true }).first().click()
  await page.getByTitle('Create new candidate implant').click()
  const runtime = () => page.evaluate(() => window.__hackPrincetonDebug!.readCanvas())
  const origin = new URL(page.url()).origin
  const projects = await (await page.request.get(`${origin}/api/projects`)).json()
  const manifest = async () => (await page.request.get(`${origin}/api/projects/${projects[0].id}`)).json()
  await expect.poll(async () => (await runtime()).visibleObjectIds.length).toBe(1)
  const before = await manifest()
  expect(await page.evaluate(() => window.__hackPrincetonDebug!.executeCommand('object.applyDraft').ok)).toBe(false)
  expect(await page.evaluate(() => 'createCandidate' in window.__hackPrincetonDebug!.ops)).toBe(false)
  expect(await page.evaluate(() => window.__hackPrincetonDebug!.executeCommand('view.standardLeft').ok)).toBe(true)
  await expect.poll(async () => (await runtime()).lastAction?.id).toBe('view.left')
  await page.keyboard.press('End')
  await expect.poll(async () => (await runtime()).lastAction?.id).toBe('view.anterior')
  const perspective = (await runtime()).camera
  await page.getByRole('button', { name: 'Orthographic projection' }).click()
  await expect.poll(async () => (await runtime()).camera.projection).toBe('orthographic')
  expect((await runtime()).camera.viewHeight).toBeCloseTo(perspective.viewHeight!, 6)
  const ruler = page.getByLabel('Orthographic ruler in millimetres')
  await expect(ruler).toBeVisible()
  let scale = (await runtime()).ruler!
  expect((await ruler.boundingBox())!.width).toBeCloseTo(scale.pixels, 1)
  expect(scale.pixelsPerMm).toBeCloseTo((await runtime()).camera.viewportHeight! / (await runtime()).camera.viewHeight!, 6)
  const canvas = page.locator('[data-testid="viewport"] canvas')
  await canvas.hover()
  await page.mouse.wheel(0, -250)
  await expect.poll(async () => (await runtime()).ruler!.pixelsPerMm).toBeGreaterThan(scale.pixelsPerMm)
  await page.setViewportSize({ width: 1440, height: 1100 })
  await expect.poll(async () => {
    const value = await runtime()
    return Math.abs(value.ruler!.pixelsPerMm - value.camera.viewportHeight! / value.camera.viewHeight!)
  }).toBeLessThan(1e-8)
  const box = (await canvas.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down({ button: 'middle' })
  await page.mouse.move(box.x + box.width / 2 + 50, box.y + box.height / 2 + 20, { steps: 4 })
  await page.mouse.up({ button: 'middle' })
  await page.getByRole('button', { name: 'Center 3D view' }).click()
  scale = (await runtime()).ruler!
  const orthographic = (await runtime()).camera
  expect(await manifest()).toEqual(before)
  await page.getByRole('button', { name: 'Perspective projection' }).click()
  await expect.poll(async () => (await runtime()).camera.projection).toBe('perspective')
  expect((await runtime()).camera.viewHeight).toBeCloseTo(orthographic.viewHeight!, 5)
  expect((await runtime()).ruler).toBeNull()
  await expect(ruler).not.toBeVisible()
  await page.getByRole('menubar', { name: 'Canvas menu' }).getByRole('button', { name: 'Object', exact: true }).click()
  await page.getByRole('button', { name: /^Transform Tool/ }).click()
  await page.getByLabel('Translate X (mm)').fill('8')
  await page.getByLabel('Translate X (mm)').press('Control+Shift+Z')
  expect(await manifest()).toEqual(before)
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect.poll(async () => (await manifest()).revisions.length).toBe(2)
  const saved = await manifest()
  await expect(page.getByLabel('Translate X (mm)')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled()
  await page.keyboard.press('Control+Backspace')
  await expect.poll(async () => (await manifest()).candidates[0].currentRevisionId).toBe(before.revisions[0].id)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled()
  await page.keyboard.press('Control+Shift+Z')
  await expect.poll(async () => (await manifest()).candidates[0].currentRevisionId).toBe(saved.revisions[1].id)
  expect((await manifest()).revisions).toEqual(saved.revisions)
  expect(errors).toEqual([])
})
