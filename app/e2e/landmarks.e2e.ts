import { test, expect } from './canvas-fixture'
import { unzipSync, strFromU8 } from 'fflate'
import { readFile } from 'node:fs/promises'

test('source slice inspection and durable landmarks measure, recover, reload and package', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  const origin = new URL(page.url()).origin
  const projects = await (await page.request.get(`${origin}/api/projects`)).json()
  const manifest = async (id = projects[0].id) => (await page.request.get(`${origin}/api/projects/${id}`)).json()
  const before = await manifest(), source = before.samples[0]
  const context = { projectId: projects[0].id, caseId: source.caseId, volumeHash: source.sourceAnatomy.volumeHash }
  const url = `${origin}/api/samples/${source.id}/landmarks`
  const bytes = await (await page.request.get(`${origin}/api/samples/${source.id}/volume`)).body()
  for (const [label, ijk] of [['A', [0, 0, 256]], ['B', [30, 40, 256]]]) {
    expect((await page.request.post(url, { data: { ...context, label, ijk } })).status()).toBe(201)
  }
  await page.getByRole('button', { name: 'Open', exact: true }).first().click()
  await page.getByRole('button', { name: 'Open 3D', exact: true }).first().click()
  const slice = page.getByLabel('Axial anatomy slice')
  await expect(slice).toBeVisible()
  await page.getByRole('button', { name: 'Landmarks', exact: true }).click()
  await page.getByLabel('First landmark', { exact: true }).selectOption({ label: 'A' })
  await page.getByLabel('Second landmark', { exact: true }).selectOption({ label: 'B' })
  await expect(page.getByLabel('Landmark distance')).toHaveText('20.00 mm')
  await page.getByRole('button', { name: 'Zoom in Axial', exact: true }).click()
  await expect(slice).toHaveAttribute('data-zoom', '1.25')
  await slice.press('ArrowUp')
  await expect(page.getByLabel('Axial slice offset')).toHaveValue('257')
  expect((await page.evaluate(() => window.__hackPrincetonDebug!.readCanvas())).activeView).toBe('axial')
  await page.getByRole('button', { name: 'Smooth interpolation Axial' }).click()
  await expect(slice).toHaveCSS('image-rendering', 'auto')
  await page.getByRole('button', { name: 'Reset Axial slice view' }).click()
  await expect(slice).toHaveAttribute('data-zoom', '1')
  const box = (await slice.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down({ button: 'middle' })
  await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 10)
  await page.mouse.up({ button: 'middle' })
  await expect(slice).not.toHaveAttribute('data-pan', '0,0')
  await page.getByRole('button', { name: 'Reset Axial slice view' }).click()
  await page.getByRole('button', { name: 'Window / Level mode', exact: true }).click()
  await page.keyboard.down('Control')
  const windowBox = (await slice.boundingBox())!
  await page.mouse.move(windowBox.x + windowBox.width * .1, windowBox.y + windowBox.height * .1)
  await page.mouse.down()
  await page.mouse.move(windowBox.x + windowBox.width * .3, windowBox.y + windowBox.height * .3)
  await page.mouse.up()
  await page.keyboard.up('Control')
  await page.getByRole('button', { name: 'Automatic window Axial' }).click()
  expect((await manifest()).landmarks).toHaveLength(2)
  expect(await (await page.request.get(`${origin}/api/samples/${source.id}/volume`)).body()).toEqual(bytes)
  await page.getByRole('button', { name: 'Place mode', exact: true }).click()
  await page.getByLabel('Keep placing points').check()
  await page.route('**/landmarks', (route) => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"controlled annotation outage"}' }) : route.continue())
  await slice.click({ position: { x: 20, y: 20 } })
  await expect(page.getByText(/controlled annotation outage/)).toBeVisible()
  expect((await manifest()).landmarks).toHaveLength(2)
  await page.unroute('**/landmarks')
  await slice.click({ position: { x: 30, y: 30 } })
  await expect.poll(async () => (await manifest()).landmarks.length).toBe(3)
  await expect(page.getByRole('button', { name: 'Place mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled()
  await slice.press('Escape')
  await expect(page.getByRole('button', { name: 'View mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Delete P1', exact: true }).click()
  await expect.poll(async () => (await manifest()).landmarks.length).toBe(2)
  await page.reload()
  await page.getByRole('button', { name: 'Open', exact: true }).first().click()
  await page.getByRole('button', { name: 'Open 3D', exact: true }).first().click()
  await page.getByRole('button', { name: 'Landmarks', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Locate A', exact: true })).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const file = (await (await downloaded).path())!
  const archive = unzipSync(await readFile(file))
  expect(JSON.parse(strFromU8(archive['package.json'])).version).toBe(2)
  expect(JSON.parse(strFromU8(archive['manifest.json'])).landmarks).toHaveLength(2)
  await page.getByRole('button', { name: 'Open Package', exact: true }).click()
  await page.getByLabel('Project package (.zip)').setInputFiles(file)
  await page.getByRole('button', { name: 'Import as new project' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'imported and opened' })).toBeVisible()
  const listed = await (await page.request.get(`${origin}/api/projects`)).json()
  const copied = await manifest(listed.find((p: { id: string }) => p.id !== projects[0].id).id)
  expect(copied.landmarks).toHaveLength(2)
  expect(copied.landmarks[0].sampleId).toBe(copied.samples[0].id)
  expect(copied.landmarks.map((p: { id: string }) => p.id)).not.toEqual((await manifest()).landmarks.map((p: { id: string }) => p.id))
  expect((await manifest()).samples).toEqual(before.samples)
  expect((await manifest()).revisions).toEqual(before.revisions)
  await page.screenshot({ path: '/private/tmp/hp-mechanics-landmarks.png' })
  expect(errors).toEqual([])
})
