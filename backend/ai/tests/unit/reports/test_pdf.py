def png(width=8, height=6, rgb=(120, 130, 140)):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    raw = b''.join(b'\x00' + bytes(rgb) * width for _ in range(height))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


FACTS = CaseFacts(case_name='Case 7 — MUG500 B0022', source_object_ids={'src'}, candidate_object_ids={'cand'},
                  annotations={'ann-rim': {'name': 'Defect rim', 'type': 'closed_curve'}})


def report(**plan_changes):
    raw = {'title': 'Right frontotemporal defect', 'summary': 'Oval defect, intact rim.',
           'findings': ['Rim thickness adequate for fixation.'],
           'measurements': [{'name': 'Defect span', 'value': '62', 'unit': 'mm', 'source': 'user-supplied'}],
           'sources': [{'title': 'PEEK cranioplasty outcomes', 'url': 'https://pubmed.ncbi.nlm.nih.gov/34567890/'}],
           'conversation_summary': 'Discussed PEEK vs titanium.',
           'callouts': [{'annotation_id': 'ann-rim', 'label': 'Defect rim'}], **plan_changes}
    store = ReportStore()
    item = store.create('conv', build_plan(raw, FACTS), case_name=FACTS.case_name,
                        context={'project_id': 'Project A', 'case_id': 'case-7', 'selected_object_id': 'cand',
                                 'revision_id': 'rev-3'})
    return item, {shot.id: png() for shot in item.plan.shots}


def pages_text(pdf: bytes) -> list[str]:
    return [page.extract_text() or '' for page in PdfReader(io.BytesIO(pdf)).pages]


AT = datetime(2026, 11, 15, 14, 30, tzinfo=timezone.utc)


class ReportPdfTest(unittest.TestCase):
    def test_s3_cover_and_footer_on_every_page(self):
        item, captures = report()
        pdf, pages = build_report_pdf(item, captures, generated_at=AT)
        self.assertTrue(pdf.startswith(b'%PDF'))
        text = pages_text(pdf)
        self.assertEqual(len(text), pages)
        self.assertIn('University of South Florida', text[0])
        self.assertIn('Cranial Reconstruction Case Report', text[0])
        self.assertIn('Case 7', text[0])
        self.assertIn('rev-3', text[0])
        self.assertIn('Generated by: AI assistant (demo)', text[0])
        for number, page in enumerate(text, start=1):
            flat = ' '.join(page.split())
            self.assertIn(f'Page {number} of {pages}', flat)
            self.assertIn('not for clinical use', flat)
            self.assertIn('University of South Florida', flat)

    def test_sections_follow_the_reference_layout(self):
        item, captures = report()
        text = ' '.join(' '.join(pages_text(build_report_pdf(item, captures, generated_at=AT)[0])).split())
        for heading in ('Preoperative Anatomy', 'Defect and Proposed Repair', 'Annotated Findings',
                        'Cross-sections', 'Findings and Conversation'):
            self.assertIn(heading, text)
        self.assertIn('Defect rim', text)
        self.assertIn('62 mm', text)
        self.assertIn('pubmed.ncbi.nlm.nih.gov/34567890', text)

    def test_a_source_url_with_markup_characters_still_builds_and_is_listed(self):
        url = 'https://example.org/search?q="peek"&lang=en'
        item, captures = report(sources=[{'title': 'Quoted query', 'url': url}])
        text = ' '.join(' '.join(pages_text(build_report_pdf(item, captures, generated_at=AT)[0])).split())
        self.assertIn('example.org/search?q="peek"&lang=en', text)

    def test_no_repair_page_without_a_candidate(self):
        facts = CaseFacts(case_name='C', source_object_ids={'src'}, candidate_object_ids=set(), annotations={})
        store = ReportStore()
        item = store.create('conv', build_plan({'title': 'T', 'summary': 'S'}, facts), case_name='C')
        text = ' '.join(pages_text(build_report_pdf(item, {s.id: png() for s in item.plan.shots}, generated_at=AT)[0]))
        self.assertNotIn('Defect and Proposed Repair', text)

    def test_s4_forbidden_brand_names_never_appear_even_if_the_model_writes_them(self):
        item, captures = report(summary='Planned like a Stryker VSP case by 3D Systems.',
                                findings=['vsp-style guide not used'])
        text = ' '.join(pages_text(build_report_pdf(item, captures, generated_at=AT)[0]))
        for name in ('Stryker', '3D Systems', 'VSP'):
            self.assertIsNone(re.search(re.escape(name), text, re.I), name)


if __name__ == '__main__':
    unittest.main()
